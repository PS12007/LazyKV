def block_pcie_curve(ctx: Mapping[str, Any]) -> str:
    curve = lookup(ctx, "phase0.analysis.pcie.curve")
    if not isinstance(curve, list):
        return f"_{NOT_MEASURED}_"
    rows = []
    for r in curve:
        rows.append(
            [iec(r["size_bytes"])]
            + [rng(r[k], lambda v: f"{v / 1e9:.2f}") for k in ("pinned_h2d", "pinned_d2h", "pageable_h2d", "pageable_d2h")]
        )
    return table(
        ["Transfer size", "Pinned H2D", "Pinned D2H", "Pageable H2D", "Pageable D2H"],
        rows,
        ["---:", "---:", "---:", "---:", "---:"],
    )


def block_pcie_knees(ctx: Mapping[str, Any]) -> str:
    p = lookup(ctx, "phase0.analysis.pcie")
    if not isinstance(p, Mapping):
        return f"_{NOT_MEASURED}_"
    rows = []
    for key, label in (("pinned_h2d", "Pinned H2D"), ("pinned_d2h", "Pinned D2H"), ("pageable_h2d", "Pageable H2D"), ("pageable_d2h", "Pageable D2H")):
        d = p[key]
        rows.append(
            [
                label,
                rng(d["asymptote_bps"], lambda v: f"{v / 1e9:.2f} GB/s"),
                rng(d["knee50_bytes"], iec),
                rng(d["knee80_bytes"], iec),
                rng(d["fit_t0_s"], lambda v: f"{v * 1e6:.0f} µs"),
                rng(d["fit_knee80_bytes"], iec),
            ]
        )
    return table(
        ["Path", "Asymptotic bandwidth", "50% knee (empirical)", "80% knee (empirical)", "Per-transfer overhead t0 (fit)", "80% knee (fit)"],
        rows,
        ["---", "---:", "---:", "---:", "---:", "---:"],
    )


