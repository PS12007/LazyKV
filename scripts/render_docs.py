# ---- formatting helpers ----------------------------------------------------------------


def gbps(v: float | None) -> str:
    return NOT_MEASURED if v is None else f"{v / 1e9:.2f}"


def rng(a: Mapping[str, Any] | None, fmt: Callable[[float], str], show_range: bool = True) -> str:
    """'median (min–max)' across independent runs."""
    if not a or not a.get("n_runs"):
        return NOT_MEASURED
    med = fmt(a["median"])
    if not show_range or a["n_runs"] < 2:
        return med
    return f"{med} ({fmt(a['min'])}–{fmt(a['max'])})"


def ms(v: float) -> str:
    return f"{v * 1e3:.3g} ms" if v < 1 else f"{v:.2f} s"


def table(header: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    align = align or ["---"] * len(header)
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


