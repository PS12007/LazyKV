    return table(
        ["Context (tokens, 1 layer)", "SDPA path", "Time per call", "KV scanned (GB/s)", "Max rel. error vs math", "Within tolerance"],
        rows,
        ["---:", "---", "---:", "---:", "---:", "---"],
    )


