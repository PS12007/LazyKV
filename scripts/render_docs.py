def block_bandwidth_ladder(ctx: Mapping[str, Any]) -> str:
    a = lookup(ctx, "phase0.analysis")
    if not isinstance(a, Mapping):
        return f"_{NOT_MEASURED}_"
    big_attn = max(a["vram"]["decode_attention"], key=lambda r: r["ctx_len"])
    best = big_attn["backends"][big_attn["best_backend"]]["kv_scan_bps"]
    cpu64 = max(a["cpu"]["partial_attn_best"], key=lambda r: r["tokens"])
    kv_fp32 = 2 * cpu64["tokens"] * 8 * 64 * 4
    t = cpu64["best_seconds"]
    # Rate is 1/time, so the fastest run (min time) is the max rate.
    cpu_rate = {"n_runs": t["n_runs"], "median": kv_fp32 / t["median"], "min": kv_fp32 / t["max"], "max": kv_fp32 / t["min"]}
    rows = [
        ["VRAM device-to-device copy", rng(a["vram"]["d2d_copy_bps"], gbps)],
        [f"GPU decode attention KV scan (`{big_attn['best_backend']}`, {big_attn['ctx_len']:,} tokens)", rng(best, gbps)],
        ["PCIe pinned H2D (asymptote)", rng(a["pcie"]["pinned_h2d"]["asymptote_bps"], gbps)],
        ["PCIe pinned D2H (asymptote)", rng(a["pcie"]["pinned_d2h"]["asymptote_bps"], gbps)],
        ["PCIe pageable H2D (asymptote)", rng(a["pcie"]["pageable_h2d"]["asymptote_bps"], gbps)],
        ["Host memcpy, 1 thread", rng(a["cpu"]["host_memcpy_bps_1thread"], gbps)],
        [f"CPU partial attention KV rate (fp32, {cpu64['tokens']:,} tokens, best threads)", rng(cpu_rate, gbps)],
    ]
    if a["nvme"].get("measured"):
        rows += [
            ["NVMe sequential read", rng(a["nvme"]["sequential_bps"], gbps)],
            ["NVMe random 128 KiB read", rng(a["nvme"]["random"]["131072"]["bps"], gbps)],
        ]
    return table(["Path", "GB/s, median (min–max) across runs"], rows, ["---", "---:"])


