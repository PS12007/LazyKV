BLOCKS: dict[str, Callable[[Mapping[str, Any]], str]] = {
    name.removeprefix("block_"): fn for name, fn in globals().items() if name.startswith("block_") and callable(fn)
}


def render_all() -> dict[Path, str]:
    ctx = load_all()
    blocks = {name: fn(ctx) for name, fn in BLOCKS.items()}
    out: dict[Path, str] = {}
    for tmpl_name, rel in OUTPUTS.items():
        tmpl_path = TEMPLATES / tmpl_name
        if not tmpl_path.exists():
            continue
        body = render(tmpl_path.read_text(encoding="utf-8"), ctx, blocks)
        out[REPO_ROOT / rel] = GENERATED_BANNER.format(name=tmpl_name) + body
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if any rendered doc differs from disk")
    args = parser.parse_args()
    stale = []
    for path, text in render_all().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("stale docs:", *[p.relative_to(REPO_ROOT) for p in stale], sep="\n  ")
        raise SystemExit(1)
    print(("checked" if args.check else "rendered"), len(render_all()), "docs;", len(stale), "changed")


if __name__ == "__main__":
    main()
